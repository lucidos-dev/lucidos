//! Content-addressed blob store for user-attached images.
//!
//! Bytes live exactly once on disk under
//! `<workspace>/data/blobs/<hh>/<hash>.<ext>` where `<hash>` is the hex
//! sha256 and `<hh>` is the first two hex chars (256-way fan-out).
//!
//! Same bytes uploaded twice = the second call is a no-op on disk.
//! Mime is sniffed server-side from magic bytes against an image-only
//! allowlist; the canonical file extension is derived from the sniffed
//! mime, not from any user-supplied filename.

use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

const BLOBS_SUBDIR: &str = "data/blobs";

/// Cache for downscaled preview JPEGs. Lives under `.lucidos/` (gitignored,
/// rebuildable) — derived from the originals, can always be regenerated by
/// re-running `get_or_create_preview`.
const PREVIEWS_SUBDIR: &str = ".lucidos/blob-previews";

/// Long-edge cap for browser-facing previews. iOS Safari/WebKit silently
/// fails to render images whose decoded bitmap exceeds its per-image
/// memory budget — the symptom is an `<img>` element that loads and then
/// renders fully black. 2048 px keeps the decoded RGBA bitmap at ~16 MB
/// (well inside WebKit's budget on iPhone) while still giving comfortable
/// headroom for the popup viewer's pinch-zoom.
pub const PREVIEW_MAX_EDGE: u32 = 2048;

const PREVIEW_MIME: &str = "image/jpeg";
const PREVIEW_EXT: &str = "jpg";
const PREVIEW_JPEG_QUALITY: u8 = 85;

/// Single source of truth for the image allowlist: (mime, canonical
/// extension). `sniff_image_mime` returns one of these mime strings;
/// `ext_for_mime` and `resolve_blob` look up the paired extension.
/// Add a new image format by appending one entry here AND extending the
/// magic-byte sniff in `sniff_image_mime`.
const ALLOWED_IMAGE_MIME_EXT: &[(&str, &str)] = &[
    ("image/png", "png"),
    ("image/jpeg", "jpg"),
    ("image/webp", "webp"),
    ("image/gif", "gif"),
    ("image/heic", "heic"),
];

#[derive(Debug)]
pub enum BlobError {
    UnsupportedMime,
    BadEncoding(String),
    Io(std::io::Error),
}

impl std::fmt::Display for BlobError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            BlobError::UnsupportedMime => write!(
                f,
                "unsupported image mime (allowed: jpeg, png, webp, gif, heic)"
            ),
            BlobError::BadEncoding(detail) => write!(f, "invalid base64 in image: {detail}"),
            BlobError::Io(e) => write!(f, "blob io error: {e}"),
        }
    }
}

impl std::error::Error for BlobError {}

impl From<std::io::Error> for BlobError {
    fn from(e: std::io::Error) -> Self {
        BlobError::Io(e)
    }
}

/// A blob's content-addressed identity plus metadata.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedBlob {
    /// sha256(bytes) as lowercase hex (64 chars).
    pub hash: String,
    /// Sniffed mime from the allowlist.
    pub mime: String,
    /// Raw byte size (not base64-inflated).
    pub byte_size: u64,
    /// Absolute path to the blob on disk.
    pub path: PathBuf,
}

/// Compute lowercase hex sha256 of `bytes`.
pub fn compute_hash(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    let digest = hasher.finalize();
    digest.iter().fold(String::with_capacity(64), |mut acc, b| {
        use std::fmt::Write as _;
        let _ = write!(acc, "{:02x}", b);
        acc
    })
}

/// Sniff a recognized image mime from magic bytes. Returns `None` for
/// anything outside the image allowlist (jpeg, png, webp, gif, heic).
///
/// HEIC detection requires looking past the leading box-size bytes to
/// the `ftyp` box brand at offset 4–11; the rest are leading-byte checks.
pub fn sniff_image_mime(bytes: &[u8]) -> Option<&'static str> {
    if bytes.len() >= 8 && bytes[..8] == [0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A] {
        return Some("image/png");
    }
    if bytes.len() >= 3 && bytes[..3] == [0xFF, 0xD8, 0xFF] {
        return Some("image/jpeg");
    }
    if bytes.len() >= 12 && &bytes[..4] == b"RIFF" && &bytes[8..12] == b"WEBP" {
        return Some("image/webp");
    }
    if bytes.len() >= 6 && (&bytes[..6] == b"GIF87a" || &bytes[..6] == b"GIF89a") {
        return Some("image/gif");
    }
    // HEIC family — bytes 4..8 are `ftyp`, bytes 8..12 are the brand.
    // Allowed brands: heic, heix, hevc, hevx, mif1, msf1 (Apple's
    // multi-image HEIF variants that PHPicker can hand us).
    if bytes.len() >= 12 && &bytes[4..8] == b"ftyp" {
        let brand = &bytes[8..12];
        if matches!(
            brand,
            b"heic" | b"heix" | b"hevc" | b"hevx" | b"mif1" | b"msf1"
        ) {
            return Some("image/heic");
        }
    }
    None
}

/// Canonical filename extension for a recognized mime. Pairs with
/// `sniff_image_mime` — the same set of types is supported.
pub fn ext_for_mime(mime: &str) -> Option<&'static str> {
    ALLOWED_IMAGE_MIME_EXT
        .iter()
        .find_map(|(m, ext)| (*m == mime).then_some(*ext))
}

/// Build the on-disk path for a blob with `hash` and `ext`.
fn blob_path(workspace: &Path, hash: &str, ext: &str) -> PathBuf {
    workspace
        .join(BLOBS_SUBDIR)
        .join(&hash[..2])
        .join(format!("{hash}.{ext}"))
}

/// Write `bytes` to the content-addressed location under
/// `<workspace>/data/blobs/`. Idempotent — if the file already exists at
/// the canonical path, it is left untouched (content-addressed, so the
/// existing bytes are by construction identical).
///
/// Returns `BlobError::UnsupportedMime` for bytes outside the image
/// allowlist (so the upload endpoint can reject with 415 before any
/// disk write).
///
/// The write goes to a sibling `.tmp-<hash>` path then renames into
/// place atomically; a crash mid-write leaves no half-written blob.
pub fn write_blob(workspace: &Path, bytes: &[u8]) -> Result<ResolvedBlob, BlobError> {
    let mime = sniff_image_mime(bytes).ok_or(BlobError::UnsupportedMime)?;
    let ext = ext_for_mime(mime).ok_or(BlobError::UnsupportedMime)?;
    let hash = compute_hash(bytes);
    let path = blob_path(workspace, &hash, ext);

    if !path.exists() {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let tmp = path.with_file_name(format!(".tmp-{hash}.{ext}"));
        std::fs::write(&tmp, bytes)?;
        std::fs::rename(&tmp, &path)?;
    }

    Ok(ResolvedBlob {
        hash,
        mime: mime.to_string(),
        byte_size: bytes.len() as u64,
        path,
    })
}

/// Resolve an existing hash to its on-disk path + mime. Returns `None`
/// when no blob with that hash exists in any of the allowlisted-extension
/// fan-out slots — callers treat that as 404.
pub fn resolve_blob(workspace: &Path, hash: &str) -> Option<ResolvedBlob> {
    if hash.len() != 64 || !hash.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    for &(mime, ext) in ALLOWED_IMAGE_MIME_EXT {
        let path = blob_path(workspace, hash, ext);
        if let Ok(meta) = std::fs::metadata(&path) {
            return Some(ResolvedBlob {
                hash: hash.to_string(),
                mime: mime.to_string(),
                byte_size: meta.len(),
                path,
            });
        }
    }
    None
}

/// Resolve `hash` and read its bytes into a base64-encoded string + mime —
/// the shape every LLM-call constructor and `walk_thread_images` user
/// branch needs. Returns `None` when the blob is missing or unreadable;
/// callers either skip silently (LLM call) or log + skip (image walks).
pub fn read_blob_as_base64(workspace: &Path, hash: &str) -> Option<(String, String)> {
    use base64::Engine as _;
    let ResolvedBlob { mime, path, .. } = resolve_blob(workspace, hash)?;
    let bytes = std::fs::read(&path).ok()?;
    Some((
        base64::engine::general_purpose::STANDARD.encode(&bytes),
        mime,
    ))
}

/// JPEG files from phone cameras store pixels in the sensor's native
/// orientation (usually landscape) and use an EXIF tag to indicate how
/// to rotate for correct display. Browsers handle this automatically
/// when consuming the original bytes, but `image::load_from_memory()`
/// ignores EXIF — so any path that decodes + re-encodes (LLM-bound
/// compression, browser-facing preview) must rotate the pixels itself
/// or the re-encoded image will be sideways.
pub fn apply_exif_orientation(raw: &[u8], img: image::DynamicImage) -> image::DynamicImage {
    let mut cursor = std::io::Cursor::new(raw);
    let exif = match exif::Reader::new().read_from_container(&mut cursor) {
        Ok(exif) => exif,
        Err(_) => return img,
    };

    let orientation = match exif.get_field(exif::Tag::Orientation, exif::In::PRIMARY) {
        Some(field) => match field.value.get_uint(0) {
            Some(v) => v,
            None => return img,
        },
        None => return img,
    };

    match orientation {
        1 => img,
        2 => img.fliph(),
        3 => img.rotate180(),
        4 => img.flipv(),
        5 => img.rotate90().fliph(),
        6 => img.rotate90(),
        7 => img.rotate270().fliph(),
        8 => img.rotate270(),
        _ => img,
    }
}

fn preview_cache_path(workspace: &Path, hash: &str, max_edge: u32) -> PathBuf {
    workspace
        .join(PREVIEWS_SUBDIR)
        .join(&hash[..2])
        .join(format!("{hash}-{max_edge}.{PREVIEW_EXT}"))
}

fn preview_blob(path: PathBuf, hash: &str, byte_size: u64) -> ResolvedBlob {
    ResolvedBlob {
        hash: hash.to_string(),
        mime: PREVIEW_MIME.to_string(),
        byte_size,
        path,
    }
}

/// Resolve `hash` and return a `<= max_edge px on long edge` JPEG suitable
/// for browser display. Caches the resized result under `.lucidos/` so the
/// second request is a plain disk read.
///
/// Returns:
///   - `Ok(None)` — no blob with that hash on disk (caller serves 404).
///   - `Ok(Some(blob))` — the original (when small enough or undecodable)
///     or the cached preview (when downscaling happened).
///   - `Err(_)` — only filesystem errors; decode failures fall back to
///     the original since iOS Safari renders most browser-supported
///     formats natively at small sizes.
///
/// Concurrent requests for the same uncached hash will each decode + write
/// independently. The atomic `tmp → rename` keeps the cache file consistent;
/// the duplicate CPU is accepted (one user-visible cache miss per blob in
/// practice — subsequent loads hit the cache).
pub fn get_or_create_preview(
    workspace: &Path,
    hash: &str,
    max_edge: u32,
) -> Result<Option<ResolvedBlob>, BlobError> {
    let original = match resolve_blob(workspace, hash) {
        Some(r) => r,
        None => return Ok(None),
    };

    let cache_path = preview_cache_path(workspace, hash, max_edge);
    if let Ok(meta) = std::fs::metadata(&cache_path) {
        return Ok(Some(preview_blob(cache_path, hash, meta.len())));
    }

    let original_bytes = std::fs::read(&original.path)?;
    let img = match image::load_from_memory(&original_bytes) {
        Ok(i) => i,
        Err(_) => return Ok(Some(original)),
    };
    let img = apply_exif_orientation(&original_bytes, img);

    if img.width().max(img.height()) <= max_edge {
        return Ok(Some(original));
    }

    let rgb = img
        .resize(max_edge, max_edge, image::imageops::FilterType::Lanczos3)
        .to_rgb8();

    let mut buf: Vec<u8> = Vec::new();
    {
        use image::codecs::jpeg::JpegEncoder;
        use image::{ColorType, ImageEncoder};
        JpegEncoder::new_with_quality(&mut buf, PREVIEW_JPEG_QUALITY)
            .write_image(
                rgb.as_raw(),
                rgb.width(),
                rgb.height(),
                ColorType::Rgb8.into(),
            )
            .map_err(|e| BlobError::Io(std::io::Error::other(e)))?;
    }

    if let Some(parent) = cache_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    // Per-call nonce in the tmp filename so two concurrent requests for the
    // same uncached hash don't share a tmp path — without it, the first to
    // rename takes the file out from under the second, whose own rename
    // then fails with ENOENT and surfaces as 500.
    let nonce = uuid::Uuid::new_v4().simple();
    let tmp = cache_path.with_file_name(format!(".tmp-{hash}-{max_edge}-{nonce}.{PREVIEW_EXT}"));
    std::fs::write(&tmp, &buf)?;
    std::fs::rename(&tmp, &cache_path)?;

    Ok(Some(preview_blob(cache_path, hash, buf.len() as u64)))
}

/// Decode `base64_str`, sniff its mime, and write it into the blob store.
/// Same idempotency guarantees as `write_blob`. Used by HTTP compat shims
/// (legacy `[{base64, mime_type}]` bodies) and by the chat send path that
/// hashes inline `ChatImage` payloads at MessageReceived emit time.
pub fn write_blob_from_base64(
    workspace: &Path,
    base64_str: &str,
) -> Result<ResolvedBlob, BlobError> {
    use base64::Engine as _;
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(base64_str)
        .map_err(|e| BlobError::BadEncoding(e.to_string()))?;
    write_blob(workspace, &bytes)
}

