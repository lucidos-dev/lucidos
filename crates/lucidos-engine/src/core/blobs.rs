    /// Encode a real JPEG of given size — needed to exercise the decode
    /// + downscale path in `get_or_create_preview`. Solid color, smallest
    ///   possible payload that still round-trips through the `image` crate.
    fn encoded_jpeg(width: u32, height: u32) -> Vec<u8> {
        use image::codecs::jpeg::JpegEncoder;
        use image::{ColorType, ImageEncoder};
        let pixels = vec![128u8; (width * height * 3) as usize];
        let mut buf: Vec<u8> = Vec::new();
        let encoder = JpegEncoder::new_with_quality(&mut buf, 70);
        encoder
            .write_image(&pixels, width, height, ColorType::Rgb8.into())
            .expect("encode jpeg");
        buf
    }

    #[test]
    fn get_or_create_preview_returns_original_when_image_within_max_edge() {
        let dir = tempfile::tempdir().unwrap();
        let bytes = encoded_jpeg(800, 600);
        let written = write_blob(dir.path(), &bytes).unwrap();

        let preview = get_or_create_preview(dir.path(), &written.hash, 2048)
            .expect("Ok for known small image")
            .expect("Some for known small image");

        assert_eq!(preview.path, written.path, "small image: serve original");
        assert_eq!(preview.mime, written.mime);
        assert_eq!(preview.byte_size, written.byte_size);
    }

    #[test]
    fn get_or_create_preview_downscales_long_edge_to_max_when_image_exceeds_it() {
        let dir = tempfile::tempdir().unwrap();
        // 4000 long edge, 3000 short edge — caps at long edge, scales short
        // proportionally → expected 2048×1536.
        let bytes = encoded_jpeg(4000, 3000);
        let written = write_blob(dir.path(), &bytes).unwrap();

        let preview = get_or_create_preview(dir.path(), &written.hash, 2048)
            .expect("Ok for known large image")
            .expect("Some for known large image");

        assert_ne!(
            preview.path, written.path,
            "large image: distinct preview file"
        );
        assert_eq!(preview.mime, "image/jpeg", "preview is always JPEG");
        assert!(preview.path.exists(), "preview file must exist on disk");
        assert!(
            preview.byte_size < written.byte_size,
            "preview should be smaller than original ({} >= {})",
            preview.byte_size,
            written.byte_size
        );

        let preview_bytes = std::fs::read(&preview.path).unwrap();
        let img = image::load_from_memory(&preview_bytes).expect("decode preview jpeg");
        assert_eq!(
            (img.width(), img.height()),
            (2048, 1536),
            "long edge clamped, aspect preserved"
        );
    }

    #[test]
    fn get_or_create_preview_caches_result_on_disk_for_second_call() {
        let dir = tempfile::tempdir().unwrap();
        let bytes = encoded_jpeg(4000, 3000);
        let written = write_blob(dir.path(), &bytes).unwrap();

        let first = get_or_create_preview(dir.path(), &written.hash, 2048)
            .unwrap()
            .unwrap();
        let mtime_first = std::fs::metadata(&first.path).unwrap().modified().unwrap();

        // Force a clock tick so we can detect a re-write — fs mtime
        // resolution is OS-dependent but always >= 1 ms in practice.
        std::thread::sleep(std::time::Duration::from_millis(20));

        let second = get_or_create_preview(dir.path(), &written.hash, 2048)
            .unwrap()
            .unwrap();
        let mtime_second = std::fs::metadata(&second.path).unwrap().modified().unwrap();

        assert_eq!(first.path, second.path);
        assert_eq!(
            mtime_first, mtime_second,
            "second call must serve from cache, not re-encode"
        );
    }

    #[test]
    fn get_or_create_preview_returns_none_for_unknown_hash() {
        let dir = tempfile::tempdir().unwrap();
        match get_or_create_preview(dir.path(), &"a".repeat(64), 2048) {
            Ok(None) => {}
            other => panic!("expected Ok(None) for unknown hash, got {other:?}"),
        }
    }

    /// HEIC bytes can't be decoded by the `image` crate (no built-in
    /// codec). Fall back to serving the original — iOS Safari renders
    /// HEIC natively, and HEIC files from iPhones are already small enough
    /// (~2 MB) to clear WebKit's per-image decode budget. Same fallback
    /// applies to any decode failure: prefer "original works" over
    /// "broken preview".
    #[test]
    fn get_or_create_preview_falls_back_to_original_when_decode_fails() {
        let dir = tempfile::tempdir().unwrap();
        let bytes = heic_bytes();
        let written = write_blob(dir.path(), &bytes).unwrap();

        let preview = get_or_create_preview(dir.path(), &written.hash, 2048)
            .expect("must not error on undecodable bytes")
            .expect("Some for an existing hash");

        assert_eq!(preview.path, written.path, "fallback: serve original bytes");
        assert_eq!(preview.mime, "image/heic");
    }
