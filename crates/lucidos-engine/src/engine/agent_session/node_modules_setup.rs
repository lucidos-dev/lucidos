use std::path::{Path, PathBuf};

/// The npm workspace members (mirrors the root `package.json` `workspaces`
/// array). npm hoists most deps to the ROOT `node_modules`, but an
/// un-hoistable package (e.g. `vitest@4`, whose tree conflicts with a
/// root-hoisted version) is installed in the MEMBER's own nested
/// `node_modules` instead. The root-only worktree provisioning misses those,
/// so we link the member trees too (see `member_node_modules_links`). A
/// `package_json_workspaces_match_const` test guards this against drift.
pub(super) const NPM_WORKSPACE_MEMBERS: &[&str] = &["crates/lucidos-app", "packages/lucidos-sdk"];

/// True if the dir looks like a real npm install — i.e. `npm install` /
/// `npm ci` ran here and wrote `.package-lock.json`. Plain directory
/// existence isn't enough: Vite creates `node_modules/.vite/` and
/// `.vite-temp/` cache dirs at runtime, which previously caused the CC
/// worktree setup to be skipped even though no packages were installed.
///
/// This marker only exists at the npm INSTALL ROOT (the repo root here) —
/// npm never writes `.package-lock.json` into a workspace MEMBER's nested
/// `node_modules`, so member trees are gated on plain existence instead (see
/// `member_node_modules_links`), not on this marker.
pub(super) fn has_install_marker(node_modules_dir: &Path) -> bool {
    node_modules_dir.join(".package-lock.json").exists()
}

/// `(src, dst)` `node_modules` pairs for every workspace MEMBER that needs
/// linking into the worktree — the un-hoistable deps the root-only hardlink
/// misses. A member qualifies when it has its own nested install in
/// `repo_root` AND the worktree copy is not already installed. The dst check
/// makes provisioning independent of the ROOT install marker: a worktree
/// created by the old root-only provisioning (root marker present, member tree
/// absent) still gets its member tree on the next spawn/resume. Members that
/// fully hoist (no nested `node_modules` in main) are skipped. Gated on the
/// SOURCE existing, not on `has_install_marker` — member trees never carry that
/// marker.
pub(super) fn member_node_modules_links(
    repo_root: &Path,
    wt_path: &Path,
) -> Vec<(PathBuf, PathBuf)> {
    NPM_WORKSPACE_MEMBERS
        .iter()
        .filter_map(|member| {
            let src = repo_root.join(member).join("node_modules");
            let dst = wt_path.join(member).join("node_modules");
            (src.is_dir() && !member_node_modules_installed(&dst)).then_some((src, dst))
        })
        .collect()
}

/// True if a worktree member `node_modules` already holds a real install.
/// Member trees carry no `.package-lock.json` marker (npm writes that only at
/// the install root), so presence is judged by any non-dot entry — a real
/// package dir. Vite's runtime cache dirs (`.vite`, `.vite-temp`) start with a
/// dot and so don't count, mirroring `has_install_marker`'s cache tolerance.
fn member_node_modules_installed(node_modules_dir: &Path) -> bool {
    std::fs::read_dir(node_modules_dir)
        .map(|mut entries| {
            entries.any(|entry| {
                entry
                    .ok()
                    .map(|e| !e.file_name().to_string_lossy().starts_with('.'))
                    .unwrap_or(false)
            })
        })
        .unwrap_or(false)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use tempfile::tempdir;

    #[test]
    fn missing_dir_has_no_marker() {
        let tmp = tempdir().unwrap();
        assert!(!has_install_marker(&tmp.path().join("node_modules")));
    }

    #[test]
    fn empty_dir_has_no_marker() {
        let tmp = tempdir().unwrap();
        let nm = tmp.path().join("node_modules");
        fs::create_dir_all(&nm).unwrap();
        assert!(!has_install_marker(&nm));
    }

    #[test]
    fn dir_with_only_vite_cache_has_no_marker() {
        // Regression: Vite creates these at dev-server startup, so the
        // directory exists but contains no real packages.
        let tmp = tempdir().unwrap();
        let nm = tmp.path().join("node_modules");
        fs::create_dir_all(nm.join(".vite")).unwrap();
        fs::create_dir_all(nm.join(".vite-temp")).unwrap();
        assert!(!has_install_marker(&nm));
    }

    #[test]
    fn dir_with_npm_lock_has_marker() {
        let tmp = tempdir().unwrap();
        let nm = tmp.path().join("node_modules");
        fs::create_dir_all(&nm).unwrap();
        fs::write(nm.join(".package-lock.json"), "{}").unwrap();
        assert!(has_install_marker(&nm));
    }

    #[test]
    fn member_links_returns_only_members_present_in_src() {
        // Repo has crates/lucidos-app/node_modules (un-hoistable vitest) but
        // NOT packages/lucidos-sdk/node_modules (fully hoisted) — the real shape.
        let repo = tempdir().unwrap();
        let wt = tempdir().unwrap();
        fs::create_dir_all(repo.path().join("crates/lucidos-app/node_modules")).unwrap();

        let links = member_node_modules_links(repo.path(), wt.path());
        assert_eq!(links.len(), 1);
        let (src, dst) = &links[0];
        assert_eq!(src, &repo.path().join("crates/lucidos-app/node_modules"));
        assert_eq!(dst, &wt.path().join("crates/lucidos-app/node_modules"));
    }

    #[test]
    fn member_links_skips_when_worktree_already_installed() {
        // Resume of a worktree already provisioned: the member tree holds real
        // packages → nothing to relink (avoids clobbering it every resume).
        let repo = tempdir().unwrap();
        let wt = tempdir().unwrap();
        fs::create_dir_all(repo.path().join("crates/lucidos-app/node_modules/vitest")).unwrap();
        fs::create_dir_all(wt.path().join("crates/lucidos-app/node_modules/vitest")).unwrap();
        assert!(member_node_modules_links(repo.path(), wt.path()).is_empty());
    }

    #[test]
    fn member_links_relinks_when_worktree_has_only_vite_cache() {
        // The worktree member dir exists but holds only Vite's runtime cache
        // (dot-dirs) — not a real install, so it must still be linked.
        let repo = tempdir().unwrap();
        let wt = tempdir().unwrap();
        fs::create_dir_all(repo.path().join("crates/lucidos-app/node_modules/vitest")).unwrap();
        fs::create_dir_all(wt.path().join("crates/lucidos-app/node_modules/.vite")).unwrap();
        assert_eq!(member_node_modules_links(repo.path(), wt.path()).len(), 1);
    }

    #[test]
    fn member_links_empty_when_all_members_hoisted() {
        // No member has its own node_modules → nothing to link (root-only case).
        let repo = tempdir().unwrap();
        let wt = tempdir().unwrap();
        fs::create_dir_all(repo.path().join("node_modules")).unwrap();
        assert!(member_node_modules_links(repo.path(), wt.path()).is_empty());
    }

    #[test]
    fn member_links_covers_multiple_members() {
        let repo = tempdir().unwrap();
        let wt = tempdir().unwrap();
        for member in NPM_WORKSPACE_MEMBERS {
            fs::create_dir_all(repo.path().join(member).join("node_modules")).unwrap();
        }
        assert_eq!(
            member_node_modules_links(repo.path(), wt.path()).len(),
            NPM_WORKSPACE_MEMBERS.len()
        );
    }

    /// Drift guard: the hardcoded member list must match the root
    /// `package.json` `workspaces` array, so a member added there can't
    /// silently escape worktree provisioning.
    #[test]
    fn package_json_workspaces_match_const() {
        // CARGO_MANIFEST_DIR is <repo>/crates/lucidos-engine, so the repo root
        // is two levels up from it.
        let repo_root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(Path::parent)
            .expect("repo root above crates/lucidos-engine")
            .to_path_buf();
        let pkg =
            fs::read_to_string(repo_root.join("package.json")).expect("read root package.json");
        let json: serde_json::Value = serde_json::from_str(&pkg).expect("parse package.json");
        let workspaces: Vec<String> = json["workspaces"]
            .as_array()
            .expect("workspaces array")
            .iter()
            .map(|v| v.as_str().expect("workspace string").to_string())
            .collect();
        let expected: Vec<String> = NPM_WORKSPACE_MEMBERS
            .iter()
            .map(|s| s.to_string())
            .collect();
        assert_eq!(
            workspaces, expected,
            "NPM_WORKSPACE_MEMBERS is out of sync with root package.json `workspaces`"
        );
    }
}
